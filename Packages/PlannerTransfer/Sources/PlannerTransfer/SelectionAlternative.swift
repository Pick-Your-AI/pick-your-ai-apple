import Foundation
import PlannerCore

/// Local consumer errors contain no supplied build, finding or private text.
public enum SelectionAlternativeError: Error, Equatable, Sendable {
    case catalogMismatch, ambiguousCatalogIdentity, ambiguousSelectionIdentity
    case missingSelection, missingCatalogItem, differentKind, unchangedCandidate
    case differentWorkloadBasis, disabledSelection, unsupportedRevision
    case reportMismatch, conflictingReportIdentity, unknownFindingParticipant, ambiguousFindingIdentity
    case evidenceMismatch, invalidLocalOwner, staleConfirmation
}

/// An uncommitted, single-slot proposal. Creating or inspecting it has no writer.
/// The unchanged workload, roles, settings, links, objectives and all locks remain
/// the basis for the candidate's independently produced reports.
public struct SelectionAlternative: Sendable {
    public let original: BuildSnapshot
    public let proposed: BuildSnapshot
    public let catalog: CatalogSnapshot
    public let selectionID: String
    public let currentItem: CatalogItem
    public let candidateItem: CatalogItem

    public static func prepare(
        build: BuildSnapshot, catalog: CatalogSnapshot, selectionID: String,
        candidateID: String, candidateVersion: String, updatedAt: String
    ) throws -> Self {
        guard build.locks.object?["catalog_snapshot_id"] == .string(catalog.id) else {
            throw SelectionAlternativeError.catalogMismatch
        }
        var selections = build.value.object!["selections"]!.array!
        var selectionIDs = Set<String>()
        for selection in selections {
            guard selectionIDs.insert(selection.object!["id"]!.string!).inserted else {
                throw SelectionAlternativeError.ambiguousSelectionIdentity
            }
        }
        guard let index = selections.firstIndex(where: { $0.object!["id"] == .string(selectionID) }) else {
            throw SelectionAlternativeError.missingSelection
        }
        var selected = selections[index].object!
        guard selected["enabled"] == .bool(true) else {
            throw SelectionAlternativeError.disabledSelection
        }
        // Changing these selections would change the workload/deployment basis
        // rather than compare an alternative under the same stated objective.
        guard selected["kind"] != .string("workload"), selected["kind"] != .string("deployment_mode") else {
            throw SelectionAlternativeError.differentWorkloadBasis
        }
        var itemKeys = Set<ItemKey>()
        for item in catalog.items {
            guard itemKeys.insert(ItemKey(item.id, item.version)).inserted else {
                throw SelectionAlternativeError.ambiguousCatalogIdentity
            }
        }
        let oldKey = ItemKey(selected["catalog_item_id"]!.string!, selected["catalog_item_version"]!.string!)
        let newKey = ItemKey(candidateID, candidateVersion)
        guard oldKey != newKey else { throw SelectionAlternativeError.unchangedCandidate }
        guard let current = catalog.items.first(where: { ItemKey($0.id, $0.version) == oldKey }),
              let candidate = catalog.items.first(where: { ItemKey($0.id, $0.version) == newKey }) else {
            throw SelectionAlternativeError.missingCatalogItem
        }
        guard selected["kind"] == .string(current.kind.rawValue), current.kind == candidate.kind else {
            throw SelectionAlternativeError.differentKind
        }
        var object = build.value.object!
        var revision = object["revision"]!.number!, one = Decimal(1), next = Decimal()
        guard NSDecimalAdd(&next, &revision, &one, .plain) == .noError, next > revision else {
            throw SelectionAlternativeError.unsupportedRevision
        }
        selected["catalog_item_id"] = .string(candidate.id)
        selected["catalog_item_version"] = .string(candidate.version)
        selections[index] = .object(selected)
        object["selections"] = .array(selections)
        object["revision"] = .number(next)
        object["updated_at"] = .string(updatedAt)
        // The old snapshot's validation/deployment label cannot qualify a changed
        // selection. This remains an uncommitted draft requiring its own checks.
        object["lifecycle"] = .string("draft")
        let encoder = JSONEncoder(); encoder.outputFormatting = [.sortedKeys]
        // The ordinary frozen boundary validates the exact generated bytes. No
        // defaults, new field, migration, evaluator or publishing path is added.
        let proposed = try BuildTransfer.snapshot(fromDraftJSON: encoder.encode(JSONValue.object(object)))
        return Self(original: build, proposed: proposed, catalog: catalog, selectionID: selectionID,
                    currentItem: current, candidateItem: candidate)
    }

    private struct ItemKey: Hashable {
        let id: Data
        let version: Data
        init(_ id: String, _ version: String) {
            self.id = Data(id.utf8); self.version = Data(version.utf8)
        }
    }
}

public enum AlternativeFindingTransition: String, Sendable {
    case baselineUnavailable, candidateUnavailable, notReportedBefore, notReportedAfter
    case persistingFailure, reportedResolved, reportedNewFailure, changed, unchanged
}

/// A join is a display comparison, never an attribution that the candidate caused
/// a finding. Missing or skipped findings do not count as a resolved failure.
public struct AlternativeFindingChange: Sendable {
    public let before: EvaluationFinding?
    public let after: EvaluationFinding?
    public let transition: AlternativeFindingTransition
}

/// A relation between the two supplied totals, not a price quote, forecast or
/// recommendation. Complete labels do not authenticate rates or arithmetic.
public enum AlternativeReportedCostRelation: String, Sendable {
    case lower, equal, higher, notComparable
}

public enum AlternativeComparisonGap: String, Sendable {
    case baselineEvaluationUnavailable, candidateEvaluationUnavailable
    case baselineEvidenceUnavailable, candidateEvidenceUnavailable
    case baselineCostUnavailable, candidateCostUnavailable
    case baselineSafeNextStepMissing, candidateSafeNextStepMissing
    case baselineEvidenceNeedsRecheck, candidateEvidenceNeedsRecheck
    case baselineReportedCostArithmeticMismatch, candidateReportedCostArithmeticMismatch
}

/// Read-only comparison of a proposed single-slot replacement. Supplied records
/// remain intact; schema validity and this local admission are not producer or
/// evidence approval. The existing evidence mapper supplies display grades.
public struct AlternativeComparison: Sendable {
    public let alternative: SelectionAlternative
    public let baselineReport: EvaluationReport?
    public let candidateReport: EvaluationReport?
    public let baselineEvidence: EvidencePresentation?
    public let candidateEvidence: EvidencePresentation?
    public let baselineCost: HistoricalCostScenario?
    public let candidateCost: HistoricalCostScenario?
    public let costComparison: HistoricalCostComparison?
    public let reportedCostRelation: AlternativeReportedCostRelation
    public let findingChanges: [AlternativeFindingChange]
    public let gaps: [AlternativeComparisonGap]
    // Every new assessment, including an identical retry, is a different review
    // generation. New evidence can never revive an earlier confirmation token.
    let generation = UUID()

    public var evidenceNotice: String {
        "Evidence grades describe the supplied component evidence, not model quality or complete evidence coverage. Missing evidence stays unknown."
    }
    public var costNotice: String {
        "Reported totals retain their own coverage, rates, methods, confidence and assumptions. A lower reported total is not a verified cheaper configuration."
    }

    public init(
        alternative: SelectionAlternative,
        baselineReport: EvaluationReport?, candidateReport: EvaluationReport?,
        baselineEvidence: EvidencePresentation?, candidateEvidence: EvidencePresentation?,
        baselineCost: CostEstimateRecord?, candidateCost: CostEstimateRecord?
    ) throws {
        try Self.validateReport(baselineReport, build: alternative.original)
        try Self.validateReport(candidateReport, build: alternative.proposed)
        if let baselineReport, let candidateReport,
           baselineReport.id.utf8.elementsEqual(candidateReport.id.utf8) {
            // The two already-bound reports name different build revisions; they
            // cannot both represent one immutable output record identity.
            throw SelectionAlternativeError.conflictingReportIdentity
        }
        try Self.validateEvidence(baselineEvidence, item: alternative.currentItem, catalog: alternative.catalog)
        try Self.validateEvidence(candidateEvidence, item: alternative.candidateItem, catalog: alternative.catalog)
        let beforeCost = try baselineCost.map { try HistoricalCostScenario(build: alternative.original, estimate: $0) }
        let afterCost = try candidateCost.map { try HistoricalCostScenario(build: alternative.proposed, estimate: $0) }
        let comparison: HistoricalCostComparison?
        if let beforeCost, let afterCost { comparison = try .compare(beforeCost, afterCost) }
        else { comparison = nil }
        self.alternative = alternative
        self.baselineReport = baselineReport; self.candidateReport = candidateReport
        self.baselineEvidence = baselineEvidence; self.candidateEvidence = candidateEvidence
        self.baselineCost = beforeCost; self.candidateCost = afterCost
        costComparison = comparison
        reportedCostRelation = try Self.costRelation(comparison)
        findingChanges = try Self.compareFindings(baselineReport, candidateReport)
        var gaps: [AlternativeComparisonGap] = []
        if baselineReport == nil { gaps.append(.baselineEvaluationUnavailable) }
        if candidateReport == nil { gaps.append(.candidateEvaluationUnavailable) }
        if baselineEvidence == nil || baselineEvidence?.displayGrade == .unavailable { gaps.append(.baselineEvidenceUnavailable) }
        if candidateEvidence == nil || candidateEvidence?.displayGrade == .unavailable { gaps.append(.candidateEvidenceUnavailable) }
        if baselineEvidence?.reviewRequirement == .recheckRequired { gaps.append(.baselineEvidenceNeedsRecheck) }
        if candidateEvidence?.reviewRequirement == .recheckRequired { gaps.append(.candidateEvidenceNeedsRecheck) }
        if baselineCost == nil { gaps.append(.baselineCostUnavailable) }
        if candidateCost == nil { gaps.append(.candidateCostUnavailable) }
        if let baselineCost, try !Self.reportedSumsAgree(baselineCost) { gaps.append(.baselineReportedCostArithmeticMismatch) }
        if let candidateCost, try !Self.reportedSumsAgree(candidateCost) { gaps.append(.candidateReportedCostArithmeticMismatch) }
        if Self.missingNextStep(baselineReport) { gaps.append(.baselineSafeNextStepMissing) }
        if Self.missingNextStep(candidateReport) { gaps.append(.candidateSafeNextStepMissing) }
        self.gaps = gaps
    }

    private static func validateReport(_ report: EvaluationReport?, build: BuildSnapshot) throws {
        guard let report else { return }
        let locks = build.locks.object!
        guard build.id.utf8.elementsEqual(report.buildID.utf8),
              build.value.object!["revision"] == .number(Decimal(report.buildRevision)),
              locks["catalog_snapshot_id"] == .string(report.catalogSnapshotID),
              locks["ruleset_id"] == .string(report.rulesetID),
              locks["ruleset_version"] == .string(report.rulesetVersion),
              locks["dependency_graph_id"] == .string(report.dependencyGraphID),
              locks["dependency_graph_revision"] == .number(Decimal(report.dependencyGraphRevision)) else {
            throw SelectionAlternativeError.reportMismatch
        }
        let ids = Set(build.value.object!["selections"]!.array!.map { $0.object!["id"]!.string! })
        guard report.findings.allSatisfy({ $0.selectionIDs.allSatisfy(ids.contains) }) else {
            throw SelectionAlternativeError.unknownFindingParticipant
        }
    }

    private static func validateEvidence(_ evidence: EvidencePresentation?, item: CatalogItem,
                                         catalog: CatalogSnapshot) throws {
        guard let evidence else { return }
        let expected = try RetainedEvidenceIdentity(componentID: item.id, componentVersion: item.version,
                                                    catalogSnapshotID: catalog.id)
        guard evidence.identity == expected else { throw SelectionAlternativeError.evidenceMismatch }
    }

    private struct FindingKey: Hashable, Comparable {
        let rule: String
        let code: String
        let participants: [String]
        init(_ finding: EvaluationFinding) {
            rule = finding.ruleID; code = finding.code; participants = finding.selectionIDs.sorted()
        }
        static func < (a: Self, b: Self) -> Bool {
            if a.rule != b.rule { return a.rule < b.rule }
            if a.code != b.code { return a.code < b.code }
            return a.participants.lexicographicallyPrecedes(b.participants)
        }
    }

    private static func keyed(_ report: EvaluationReport?) throws -> [FindingKey: EvaluationFinding] {
        var result: [FindingKey: EvaluationFinding] = [:]
        for finding in report?.findings ?? [] {
            guard result.updateValue(finding, forKey: FindingKey(finding)) == nil else {
                throw SelectionAlternativeError.ambiguousFindingIdentity
            }
        }
        return result
    }

    private static func compareFindings(_ before: EvaluationReport?, _ after: EvaluationReport?) throws -> [AlternativeFindingChange] {
        let left = try keyed(before), right = try keyed(after)
        return Set(left.keys).union(right.keys).sorted().map { key in
            let a = left[key], b = right[key]
            let transition: AlternativeFindingTransition
            if before == nil { transition = .baselineUnavailable }
            else if after == nil { transition = .candidateUnavailable }
            else if a == nil { transition = .notReportedBefore }
            else if b == nil { transition = .notReportedAfter }
            else if a!.outcome == .fail && b!.outcome == .fail { transition = .persistingFailure }
            else if a!.outcome == .fail && b!.outcome == .pass { transition = .reportedResolved }
            else if a!.outcome == .pass && b!.outcome == .fail { transition = .reportedNewFailure }
            else { transition = sameFinding(a!, b!) ? .unchanged : .changed }
            return AlternativeFindingChange(before: a, after: b, transition: transition)
        }
    }

    private static func sameFinding(_ a: EvaluationFinding, _ b: EvaluationFinding) -> Bool {
        // Frozen IDs/enums are ASCII and nested EvaluationJSONValue equality is
        // already exact. Supplement the DTO's synthesized equality for its four
        // free-form strings; canonically equivalent text is not the same record.
        guard a == b, a.message.utf8.elementsEqual(b.message.utf8),
              sameText(a.remediation, b.remediation) else { return false }
        switch (a.evidence, b.evidence) {
        case (nil, nil): return true
        case let (left?, right?):
            return left.count == right.count && zip(left, right).allSatisfy { pair in
                pair.0.path.utf8.elementsEqual(pair.1.path.utf8) &&
                    sameText(pair.0.sourceVersion, pair.1.sourceVersion)
            }
        default: return false
        }
    }

    private static func sameText(_ a: String?, _ b: String?) -> Bool {
        switch (a, b) {
        case (nil, nil): return true
        case let (left?, right?): return left.utf8.elementsEqual(right.utf8)
        default: return false
        }
    }

    private static func missingNextStep(_ report: EvaluationReport?) -> Bool {
        report?.findings.contains {
            ($0.outcome == .fail || $0.outcome == .unknown) &&
                ($0.remediation?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ?? true)
        } ?? false
    }

    private static func costRelation(_ comparison: HistoricalCostComparison?) throws -> AlternativeReportedCostRelation {
        guard let comparison, comparison.cautions == [.reportedValuesOnly] else { return .notComparable }
        guard try reportedSumsAgree(comparison.before.estimate),
              try reportedSumsAgree(comparison.after.estimate) else { return .notComparable }
        let before = try ContractDecimal(comparison.before.estimate.total.amount)
        let after = try ContractDecimal(comparison.after.estimate.total.amount)
        return after < before ? .lower : before < after ? .higher : .equal
    }

    private static func reportedSumsAgree(_ estimate: CostEstimateRecord) throws -> Bool {
        var sum = try ContractDecimal("0")
        for line in estimate.lineItems { sum = sum + (try ContractDecimal(line.amount.amount)) }
        let subtotal = try ContractDecimal(estimate.subtotal.amount)
        let tax = try ContractDecimal(estimate.tax.amount), total = try ContractDecimal(estimate.total.amount)
        return sum == subtotal && subtotal + tax == total
    }
}
